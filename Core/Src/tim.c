// 定时器中断回调函数 *******************************************************************************************
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  //按键20ms消抖 **********************************************************************************
  if (htim->Instance == TIM4)
  {
    uint8_t is_any_key_processing = 0; // 标记是否有按键在消抖

    // 遍历所有按键，执行20ms消抖检测
    for (uint8_t i = 0; i < KEY_NUM; i++)
    {
      if (keys[i].state == KEY_DETECTED)
      {
        // 20ms后检测按键状态：确认是否真的按下
        if (HAL_GPIO_ReadPin(keys[i].GPIOx, keys[i].GPIO_Pin) == GPIO_PIN_RESET)
        {
          keys[i].state = KEY_READY; // 消抖完成，标记可处理
        }
        else
        {
          keys[i].state = KEY_IDLE; 
        }
        is_any_key_processing = 1;
      }
    }

    // 无按键消抖时，停止定时器（节省资源）
    if (!is_any_key_processing) 
    {
      HAL_TIM_Base_Stop_IT(&htim4);
    }
  }


  //发起DMA读取磁编码角度值 ***************************************************************************
  if (htim->Instance == TIM8)
  {
    // 发起DMA读取，同步adc读取
    MT6816_Start_DMA_Read();
  }


  //计算电机转动角速度 ********************************************************************************
  if (htim->Instance == TIM7)
  {
    static float encoder_angle_last = 0;

    // 防止浮点计算或采集误差，超过2PI范围
    encoder_angle = min(encoder_angle, 2*PI);
    encoder_angle = max(encoder_angle, -2*PI);

    // encoder_angle_last默认值是0，不能用于计算，需要赋初值
    if (speed_cal_reset_flag)
    {
      // 初始化关键变量（复位后重新赋值，而非依赖static初值）
      encoder_angle_last = encoder_angle;    // 赋当前编码器实时角度为初值
      // 清零复位标志（仅初始化一次）
      speed_cal_reset_flag = 0;
    }
    
    float diff_angle = cycle_diff(encoder_angle - encoder_angle_last, 2*PI);
    // 电角度反向了，这里差值也反向
    diff_angle = -diff_angle;
    encoder_angle_last = encoder_angle;
    float _motor_speed = diff_angle * SPEED_CALCU_FREQ;
    //motor_speed = low_pass_filter(_motor_speed, motor_speed, motor_speed_low_pass_filter_alpha);
    motor_speed = kalman_filter_calc(&motor_speed_kalman_filter, _motor_speed);
  }
}

